'use client';

import { useState, useMemo } from 'react';
import { queryPredictions } from '@/lib/predictions';
import { TAXONOMY } from '@/lib/data';
import { Search, ChevronLeft, ChevronRight, ChevronsLeft, ChevronsRight } from 'lucide-react';

export default function Explorer() {
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedClass, setSelectedClass] = useState('all');
  const [page, setPage] = useState(1);
  const pageSize = 25;

  const result = useMemo(() => {
    return queryPredictions(searchQuery, selectedClass, page, pageSize);
  }, [searchQuery, selectedClass, page]);

  // Color lookup helper
  const classColorMap = useMemo(() => {
    const map: Record<string, string> = {};
    for (const c of TAXONOMY) {
      map[c.id] = c.color;
    }
    return map;
  }, []);

  const classDisplayMap = useMemo(() => {
    const map: Record<string, string> = {};
    for (const c of TAXONOMY) {
      map[c.id] = c.display;
    }
    return map;
  }, []);

  const handleSearchChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    setSearchQuery(e.target.value);
    setPage(1);
  };

  const handleClassChange = (newClass: string) => {
    setSelectedClass(newClass);
    setPage(1);
  };

  return (
    <section id="explorer" className="py-8 border-t border-creamy">
      <div className="flex flex-wrap items-baseline justify-between gap-2 mb-6">
        <div>
          <span className="text-xs font-bold uppercase tracking-wider text-creamy-accent">
            Stellar Inspection &amp; Telemetry
          </span>
          <h2 className="text-2xl font-bold tracking-tight text-creamy-primary mt-0.5">
            Prediction Explorer
          </h2>
          <p className="text-xs text-creamy-secondary mt-1">
            Browse, filter, and inspect all 7,000 blind test stellar target predictions generated by the approved champion pipeline.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <span className="px-2.5 py-1 text-xs font-mono font-semibold rounded bg-[#EAEFE8] text-[#3F6350] border border-[#C8D7C4]">
            Showing {result.total.toLocaleString()} Matching Stars
          </span>
        </div>
      </div>

      {/* Filter and Search Bar Card */}
      <div className="scientific-card p-4 mb-4">
        <div className="flex flex-col sm:flex-row gap-3 items-center justify-between">
          {/* Search Input */}
          <div className="relative w-full sm:w-72">
            <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-creamy-muted" />
            <input
              type="text"
              placeholder="Search by Star ID (e.g. TIC9144)..."
              value={searchQuery}
              onChange={handleSearchChange}
              className="w-full pl-9 pr-3 py-2 text-xs rounded-lg border border-creamy bg-[#FFFDF8] focus:outline-none focus:ring-1 focus:ring-creamy-accent text-creamy-primary placeholder:text-creamy-muted font-mono"
            />
          </div>

          {/* Class Filter Selector */}
          <div className="flex items-center gap-2 w-full sm:w-auto overflow-x-auto pb-1 sm:pb-0">
            <span className="text-[11px] font-semibold uppercase text-creamy-muted shrink-0 hidden sm:inline">
              Filter:
            </span>
            <button
              type="button"
              onClick={() => handleClassChange('all')}
              className={`px-2.5 py-1.5 rounded text-xs font-medium shrink-0 transition-colors ${
                selectedClass === 'all'
                  ? 'bg-creamy-accent text-white'
                  : 'bg-[#F0EBDD] text-creamy-secondary hover:bg-[#EAEFE8]'
              }`}
            >
              All Classes ({result.countsByClass ? Object.values(result.countsByClass).reduce((a, b) => a + b, 0).toLocaleString() : '7,000'})
            </button>

            {TAXONOMY.map((c) => (
              <button
                key={c.id}
                type="button"
                onClick={() => handleClassChange(c.id)}
                className={`px-2.5 py-1.5 rounded text-xs font-medium shrink-0 transition-colors flex items-center gap-1.5 ${
                  selectedClass === c.id
                    ? 'text-white'
                    : 'bg-[#FFFDF8] border border-creamy text-creamy-secondary hover:bg-[#F0EBDD]'
                }`}
                style={selectedClass === c.id ? { backgroundColor: c.color } : {}}
              >
                <span className="w-2 h-2 rounded-full" style={{ backgroundColor: c.color }} />
                <span>{c.name}</span>
                <span className="text-[10px] opacity-80">({c.count})</span>
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Predictions Table Card */}
      <div className="scientific-card p-4">
        <div className="overflow-x-auto">
          <table className="w-full text-xs text-left">
            <thead>
              <tr className="border-b border-creamy text-creamy-secondary font-mono">
                <th className="py-2.5 px-3 w-16">#</th>
                <th className="py-2.5 px-3 w-48">Stellar Target ID</th>
                <th className="py-2.5 px-3 w-44">Predicted Class</th>
                <th className="py-2.5 px-3">Astrophysical Interpretation</th>
                <th className="py-2.5 px-3 text-right w-28">Status</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-creamy-subtle">
              {result.items.length === 0 ? (
                <tr>
                  <td colSpan={5} className="py-8 text-center text-creamy-muted">
                    No target stars match your filter query. Try clearing the search query or class filter.
                  </td>
                </tr>
              ) : (
                result.items.map((item, idx) => {
                  const itemIndex = (result.page - 1) * result.pageSize + idx + 1;
                  const color = classColorMap[item.label] || '#647C70';
                  const display = classDisplayMap[item.label] || item.label;

                  return (
                    <tr key={item.id} className="hover:bg-[#FAF6ED] transition-colors">
                      <td className="py-2.5 px-3 font-mono text-creamy-muted">
                        {itemIndex.toLocaleString()}
                      </td>
                      <td className="py-2.5 px-3 font-mono font-bold text-creamy-primary">
                        {item.id}
                      </td>
                      <td className="py-2.5 px-3">
                        <span
                          className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded text-[11px] font-mono font-semibold"
                          style={{
                            backgroundColor: `${color}15`,
                            color: color,
                            border: `1px solid ${color}40`,
                          }}
                        >
                          <span className="w-1.5 h-1.5 rounded-full" style={{ backgroundColor: color }} />
                          {item.label}
                        </span>
                      </td>
                      <td className="py-2.5 px-3 text-creamy-secondary">
                        {display}
                      </td>
                      <td className="py-2.5 px-3 text-right">
                        <span className="text-[10px] font-mono font-semibold px-1.5 py-0.5 rounded bg-[#EAEFE8] text-[#3F6350]">
                          Approved
                        </span>
                      </td>
                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>

        {/* Pagination Bar */}
        <div className="mt-4 pt-3 border-t border-creamy flex flex-col sm:flex-row items-center justify-between gap-3 text-xs text-creamy-secondary">
          <div className="font-mono text-[11px]">
            Page <strong className="text-creamy-primary">{result.page}</strong> of{' '}
            <strong className="text-creamy-primary">{result.totalPages}</strong> (
            {((result.page - 1) * result.pageSize + 1).toLocaleString()} -{' '}
            {Math.min(result.page * result.pageSize, result.total).toLocaleString()} of{' '}
            {result.total.toLocaleString()} stars)
          </div>

          <div className="flex items-center gap-1">
            <button
              type="button"
              onClick={() => setPage(1)}
              disabled={result.page <= 1}
              className="p-1.5 rounded border border-creamy bg-[#FFFDF8] disabled:opacity-40 hover:bg-[#F0EBDD] transition-colors"
              title="First Page"
            >
              <ChevronsLeft className="w-3.5 h-3.5" />
            </button>
            <button
              type="button"
              onClick={() => setPage((p) => Math.max(1, p - 1))}
              disabled={result.page <= 1}
              className="px-2.5 py-1.5 rounded border border-creamy bg-[#FFFDF8] disabled:opacity-40 hover:bg-[#F0EBDD] transition-colors flex items-center gap-1"
            >
              <ChevronLeft className="w-3.5 h-3.5" />
              <span>Previous</span>
            </button>

            <span className="px-3 py-1 font-mono font-semibold text-creamy-primary">
              {result.page} / {result.totalPages}
            </span>

            <button
              type="button"
              onClick={() => setPage((p) => Math.min(result.totalPages, p + 1))}
              disabled={result.page >= result.totalPages}
              className="px-2.5 py-1.5 rounded border border-creamy bg-[#FFFDF8] disabled:opacity-40 hover:bg-[#F0EBDD] transition-colors flex items-center gap-1"
            >
              <span>Next</span>
              <ChevronRight className="w-3.5 h-3.5" />
            </button>
            <button
              type="button"
              onClick={() => setPage(result.totalPages)}
              disabled={result.page >= result.totalPages}
              className="p-1.5 rounded border border-creamy bg-[#FFFDF8] disabled:opacity-40 hover:bg-[#F0EBDD] transition-colors"
              title="Last Page"
            >
              <ChevronsRight className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>
      </div>
    </section>
  );
}
